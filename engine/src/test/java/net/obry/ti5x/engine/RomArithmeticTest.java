  /* the ROM algorithm one addition at a time, as in the microcode */

  private static long reference(long First, long Second, int[] Carry) {
    final long Top = 10_000_000_000_000L;
    long Acc = 0;
    long A = First;
    long B = Second;
    boolean Overflow = false;
    boolean FirstDigit = true;
    while (true) {
      if (!FirstDigit) {
        if (A == 0)
          break;
        if (Overflow) {
          B *= 10;
          Overflow = false;
        } else {
          Acc /= 10;
        }
      }
      FirstDigit = false;
      final long Digit = A % 10;
      A /= 10;
      for (int i = 0; i < Digit; i++) {
        Acc += B;
        if (Acc >= Top) {
          Acc /= 10;
          B /= 10;
          Overflow = true;
        }
      }
    }
    Carry[0] = Overflow ? 1 : 0;
    return Acc;
  }

  @Test
  void sameAsOneAdditionAtATime() {
    final Random Rnd = new Random(59);
    final int[] C1 = new int[1];
    final int[] C2 = new int[1];
    for (int i = 0; i < 200_000; i++) {
      long A = 1_000_000_000_000L + (long) (Rnd.nextDouble() * 8_999_999_999_999L);
      final long B = 1_000_000_000_000L + (long) (Rnd.nextDouble() * 8_999_999_999_999L);
      if (Rnd.nextBoolean())
        A = A / 1_000_000_000L * 1_000_000_000L;
      final long R = Number.romMultMantissa(A, B, C1);
      assertEquals(reference(A, B, C2), R, A + " x " + B);
      assertEquals(C2[0], C1[0], A + " x " + B);
    }
  }

