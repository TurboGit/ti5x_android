package net.obry.ti5x.engine;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.FileInputStream;
import java.io.IOException;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.zip.ZipFile;

import org.junit.jupiter.api.Test;

class ProgramFilesTest {
  /* files generated by the app build (preprocess task) from modules/ and programs/ */
  private static final File RawDir = new File("../app/src/main/res/raw");

  private static List<File> RawFiles(String Ext) {
    final File[] Files = RawDir.listFiles((Dir, Name) -> Name.endsWith(Ext));
    assumeTrue(Files != null && Files.length > 0, "no " + Ext + " in " + RawDir + ", build the app first");
    final List<File> Result = new ArrayList<>();
    Collections.addAll(Result, Files);
    return Result;
  }

  private static int CountPrograms(File F) throws IOException {
    int Count = 0;
    try (ZipFile Zip = new ZipFile(F)) {
      for (int i = 0; i < 100; i++) {
        if (Zip.getEntry(String.format("prog%02d", i)) != null) {
          Count++;
        }
      }
    }
    return Count;
  }

  private static byte[] SaveState(Calculator Engine) {
    final ByteArrayOutputStream Out = new ByteArrayOutputStream();
    ProgramFiles.Save(Engine.Calc, null, false, true, Out);
    return Out.toByteArray();
  }

  private static String Prog00(byte[] Archive) {
    /* the XML state component of a saved archive */
    try (java.util.zip.ZipInputStream In =
            new java.util.zip.ZipInputStream(new ByteArrayInputStream(Archive))) {
      for (; ; ) {
        final java.util.zip.ZipEntry Entry = In.getNextEntry();
        if (Entry == null)
          return null;
        if (Entry.getName().equals("prog00"))
          /* an empty paper line is reloaded as a line of blanks */
          return new String(ProgramFiles.ReadAll(In)).replaceAll("<line> *</line>", "<line></line>");
      }
    } catch (IOException Failed) {
      throw new RuntimeException(Failed);
    }
  }

  @Test
  void loadsAllLibraries() throws IOException {
    for (File F : RawFiles(".ti5l")) {
      final Calculator Engine = new TestHost().NewCalculator();
      ProgramFiles.Load(Engine.Calc, null, new FileInputStream(F), true, false);
      int Banks = 0;
      for (int i = 1; i < Engine.Calc.MaxBanks; i++) {
        if (Engine.Calc.Bank[i] != null) {
          assertNotNull(Engine.Calc.Bank[i].Program, F + " bank " + i);
          Banks++;
        }
      }
      assertEquals(CountPrograms(F), Banks, F.getName());
    }
  }

  @Test
  void loadsAllPrograms() throws IOException {
    for (File F : RawFiles(".ti5p")) {
      final Calculator Engine = new TestHost().NewCalculator();
      ProgramFiles.Load(Engine.Calc, null, new FileInputStream(F), false, false);
      boolean NonZero = false;
      for (byte Op : Engine.Calc.Program) {
        NonZero |= Op != 0;
      }
      assertTrue(NonZero, F.getName() + " has an empty program");
    }
  }

  @Test
  void masterLibraryRuns() throws IOException {
    final File Ml = new File(RawDir, "ml.ti5l");
    assumeTrue(Ml.exists(), "build the app first");
    final Calculator Engine = new TestHost().NewCalculator();
    ProgramFiles.Load(Engine.Calc, null, new FileInputStream(Ml), true, false);
    assertNotNull(Engine.Calc.ModuleHelp);
    assertNotNull(Engine.Calc.Bank[1].Card);
    /* 2nd Pgm 01 selects ML-01 */
    Engine.Calc.SelectProgram(1, false);
    assertEquals(1, Engine.Calc.CurBank);
    assertFalse(Engine.Calc.InErrorState());
  }

  @Test
  void stateRoundTrip() {
    final TestHost Host = new TestHost();
    final Calculator Engine = Host.NewCalculator();
    final State Calc = Engine.Calc;
    Calc.Memory[7] = new Number(3.25);
    Calc.Memory[99] = new Number(-0.000123);
    Calc.Memory[50] = new Number("-1E-20"); /* lost by the fixed 16 decimals format */
    Calc.Memory[51] = new Number("1.234567890123E-10"); /* digits lost by the same */
    Calc.X = new Number("2.5E-30");
    Calc.T = new Number("-7.000000000001E-12");
    Calc.Program[0] = 85;
    Calc.Program[1] = 1;
    Calc.Program[2] = 95;
    Calc.Program[3] = 91;
    Calc.Flag[3] = true;
    Calc.CurAng = State.ANG_RAD;
    Calc.SetDisplayMode(State.FORMAT_ENG, 4);
    Engine.Keys.AltState = true;
    Calc.PrintDisplay(true, false, true, "");

    final byte[] Saved = SaveState(Engine);

    final Calculator Copy = new TestHost().NewCalculator();
    ProgramFiles.Load(Copy.Calc, null, new ByteArrayInputStream(Saved), false, true);
    assertEquals(3.25, Copy.Calc.Memory[7].get());
    assertEquals(-0.000123, Copy.Calc.Memory[99].get());
    assertTrue(Calc.Memory[50].isEqual(Copy.Calc.Memory[50]), Copy.Calc.Memory[50].toStateString());
    assertTrue(Calc.Memory[51].isEqual(Copy.Calc.Memory[51]), Copy.Calc.Memory[51].toStateString());
    assertTrue(Calc.X.isEqual(Copy.Calc.X), Copy.Calc.X.toStateString());
    assertTrue(Calc.T.isEqual(Copy.Calc.T), Copy.Calc.T.toStateString());
    assertArrayEquals(Calc.Program, Copy.Calc.Program);
    assertTrue(Copy.Calc.Flag[3]);
    assertEquals(State.ANG_RAD, Copy.Calc.CurAng);
    assertEquals(State.FORMAT_ENG, Copy.Calc.CurFormat);
    assertEquals(4, Copy.Calc.CurNrDecimals);
    assertTrue(Copy.Keys.AltState);
    assertEquals(Engine.Print.Content.size(), Copy.Print.Content.size());

    /* saving the loaded state gives the same content */
    assertEquals(Prog00(Saved), Prog00(SaveState(Copy)));
  }

  @Test
  void bankRoundTrip() {
    final Calculator Engine = new TestHost().NewCalculator();
    final State Calc = Engine.Calc;
    for (int i = 0; i < 240; i++) {
      Calc.Program[i] = (byte) (i % 100);
    }
    Calc.Memory[95] = new Number(42); /* bank 1 holds memories 90 .. 119 */
    Calc.Memory[96] = new Number("3.000000000007E-50");

    final ByteArrayOutputStream Out = new ByteArrayOutputStream();
    ProgramFiles.SaveBank(Calc, Out, 1, 12);

    final Calculator Copy = new TestHost().NewCalculator();
    ProgramFiles.LoadBank(Copy.Calc, new ByteArrayInputStream(Out.toByteArray()), 1, 12);
    assertTrue(Copy.Calc.Store.Contains(12));
    Copy.Calc.Store.Get(12).LoadCard(Copy.Calc.Memory, Copy.Calc.Program, 0);
    assertArrayEquals
       (
          java.util.Arrays.copyOf(Calc.Program, 240),
          java.util.Arrays.copyOf(Copy.Calc.Program, 240)
       );
    assertEquals(42.0, Copy.Calc.Memory[95].get());
    assertTrue(Calc.Memory[96].isEqual(Copy.Calc.Memory[96]), Copy.Calc.Memory[96].toStateString());
  }

  @Test
  void paperDoesNotGrowOnRestore() {
    /* the app restores the saved state into a new calculator on each start */
    Calculator Engine = new TestHost().NewCalculator();
    Engine.Calc.PrintDisplay(true, false, true, "");
    final int Lines = Engine.Print.Content.size();
    for (int i = 0; i < 3; i++) {
      final byte[] Saved = SaveState(Engine);
      Engine = new TestHost().NewCalculator();
      ProgramFiles.Load(Engine.Calc, null, new ByteArrayInputStream(Saved), false, true);
      assertEquals(Lines, Engine.Print.Content.size(), "after restore " + (i + 1));
    }
  }

  @Test
  void readsOldNumberFormat() {
    /* state saved by earlier versions: memories with 16 fixed decimals */
    final String Xml =
         "<state>\n    <calc>\n        <mem>\n"
       + "            3.2500000000000000\n"
       + "            -0.0001230000000000\n"
       + "            1234567890123.0000000000000000\n"
       + "        </mem>\n    </calc>\n</state>\n";
    final ByteArrayOutputStream Archive = new ByteArrayOutputStream();
    try (java.util.zip.ZipOutputStream Zip = new java.util.zip.ZipOutputStream(Archive)) {
      final java.util.zip.ZipEntry Mime = new java.util.zip.ZipEntry("mimetype");
      final byte[] MimeBytes = ProgramFiles.CalcMimeType.getBytes();
      final java.util.zip.CRC32 Crc = new java.util.zip.CRC32();
      Crc.update(MimeBytes);
      Mime.setMethod(java.util.zip.ZipEntry.STORED);
      Mime.setSize(MimeBytes.length);
      Mime.setCrc(Crc.getValue());
      Zip.putNextEntry(Mime);
      Zip.write(MimeBytes);
      Zip.putNextEntry(new java.util.zip.ZipEntry("prog00"));
      Zip.write(Xml.getBytes());
    } catch (IOException Failed) {
      throw new RuntimeException(Failed);
    }
    final Calculator Engine = new TestHost().NewCalculator();
    ProgramFiles.Load(Engine.Calc, null, new ByteArrayInputStream(Archive.toByteArray()), false, true);
    assertEquals(3.25, Engine.Calc.Memory[0].get());
    assertEquals(-0.000123, Engine.Calc.Memory[1].get());
    assertEquals(1234567890123.0, Engine.Calc.Memory[2].get());
  }

  @Test
  void rejectsNonArchive() {
    final Calculator Engine = new TestHost().NewCalculator();
    assertThrows
       (
          DataFormatException.class,
          () -> ProgramFiles.Load
             (
                Engine.Calc, null, new ByteArrayInputStream("not a zip".getBytes()), false, false
             )
       );
    assertNull(Engine.Calc.Bank[0].Card);
  }
}
